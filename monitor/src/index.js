// ─────────────────────────────────────────────────────────────
// HELPERS
// ─────────────────────────────────────────────────────────────

function parseTargets(env) {
  if (!env.TARGETS) return DEFAULT_TARGETS;
  try {
    const parsed = JSON.parse(env.TARGETS);
    return Array.isArray(parsed) && parsed.length ? parsed : DEFAULT_TARGETS;
  } catch {
    console.error('[monitor] TARGETS is not valid JSON — falling back to defaults');
    return DEFAULT_TARGETS;
  }
}

async function kvGet(env, key, fallback) {
  const raw = await env.MONITOR.get(key);
  if (!raw) return fallback;
  try {
    return JSON.parse(raw);
  } catch {
    return fallback;
  }
}

function json(data, status = 200) {
  return new Response(JSON.stringify(data, null, 2), {
    status,
    headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' }
  });
}

function fmt(iso) {
  if (!iso) return 'unknown';
  return iso.replace('T', ' ').replace(/\.\d+Z$/, ' UTC');
}

function esc(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
